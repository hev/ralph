func TestCopyFile(t *testing.T) {
	// Create a temp directory for testing
	tmpDir := t.TempDir()

	tests := []struct {
		name        string
		srcContent  string
		srcExists   bool
		dstWritable bool
		wantErr     bool
	}{
		{
			name:        "successful copy",
			srcContent:  "hello world",
			srcExists:   true,
			dstWritable: true,
			wantErr:     false,
		},
		{
			name:        "empty file",
			srcContent:  "",
			srcExists:   true,
			dstWritable: true,
			wantErr:     false,
		},
		{
			name:        "large content",
			srcContent:  strings.Repeat("a", 10000),
			srcExists:   true,
			dstWritable: true,
			wantErr:     false,
		},
		{
			name:        "multiline content",
			srcContent:  "line1\nline2\nline3",
			srcExists:   true,
			dstWritable: true,
			wantErr:     false,
		},
		{
			name:        "source does not exist",
			srcContent:  "",
			srcExists:   false,
			dstWritable: true,
			wantErr:     true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			srcPath := filepath.Join(tmpDir, tt.name+"_src.txt")
			dstPath := filepath.Join(tmpDir, tt.name+"_dst.txt")

			// Create source file if it should exist
			if tt.srcExists {
				if err := os.WriteFile(srcPath, []byte(tt.srcContent), 0644); err != nil {
					t.Fatalf("Failed to create source file: %v", err)
				}
			}

			// Run copyFile
			err := copyFile(srcPath, dstPath)

			// Check error expectation
			if (err != nil) != tt.wantErr {
				t.Errorf("copyFile() error = %v, wantErr %v", err, tt.wantErr)
				return
			}

			// If no error expected, verify the copy
			if !tt.wantErr {
				dstContent, err := os.ReadFile(dstPath)
				if err != nil {
					t.Errorf("Failed to read destination file: %v", err)
					return
				}

				if string(dstContent) != tt.srcContent {
					t.Errorf("copyFile() content = %q, want %q", string(dstContent), tt.srcContent)
				}
			}
		})
	}
}

